/**
 * Ensures title strings use standard sentence case (not Title Case where every word is capitalized).
 * Example: "Planificación De Compras" -> "Planificación de compras"
 */
export function toSentenceCase(text: string): string {
	if (!text || typeof text !== "string") return text;
	const trimmed = text.trim();
	if (!trimmed) return "";
	return trimmed.charAt(0).toUpperCase() + trimmed.slice(1).toLowerCase();
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
	const [language, setLanguage] = useLocalStorage<Language>("gigblade_language", "es");

	// Update html lang attribute dynamically
	useEffect(() => {
		if (typeof document !== "undefined") {
			document.documentElement.lang = language;
		}
	}, [language]);

	const t = useCallback(
		(key: string, fallback?: string): string => {
			const dict = translations[language] || translations.es;
			if (dict[key]) return dict[key];
			if (translations.es[key]) return translations.es[key];
			return fallback || key;
		},
		[language],
	);

	return (
		<LanguageContext.Provider
			value={{
				language,
				setLanguage,
				t,
				toSentenceCase,
			}}
		>
			{children}
		</LanguageContext.Provider>
	);
}

export function useLanguage(): LanguageContextType {
	const context = useContext(LanguageContext);
	if (!context) {
		return {
			language: "es",
			setLanguage: () => {},
			t: (key: string, fallback?: string) => fallback || key,
			toSentenceCase,
		};
	}
	return context;
}
